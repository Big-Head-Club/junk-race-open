// Drive a speed run headless: home -> run with ghosts -> results -> submit. Screenshots in shots/.
//   bun tools/speed-flow.mjs [w] [h]
import { chromium } from "playwright"
const [w = 1440, h = 900] = process.argv.slice(2)
const browser = await chromium.launch({ args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader"] })
const page = await browser.newPage({ viewport: { width: +w, height: +h } })
const errors = []
page.on("pageerror", (e) => errors.push("pageerror: " + e.message))
page.on("console", (m) => { if (m.type() === "error") errors.push("console: " + m.text()) })
await page.goto("http://localhost:4731/")
await page.evaluate(() => { localStorage.setItem("junk-race:mode", '"daily"') })
await page.reload()
await page.waitForTimeout(6000)
await page.screenshot({ path: `shots/speed-0-home-${w}.png` })
await page.click("#goRace")
await page.waitForFunction(() => __game.race?.phase === "race", null, { timeout: 60000 })
await page.evaluate(() => { __game.race.karts[0].who = "bot" })
await page.waitForTimeout(7000)
await page.screenshot({ path: `shots/speed-1-run-${w}.png` })
const mid = await page.evaluate(() => ({ t: __game.race.raceT.toFixed(1), ghosts: __game.run.ghosts.length, frames: __game.run.rec.f.length / 7, hud: document.getElementById("place").textContent + " | " + document.getElementById("lap").textContent }))
console.log(JSON.stringify(mid))
await page.evaluate(() => { const r = __game.race; r.karts[0].prog = r.circuit.length + 1 })
await page.waitForTimeout(3500)
await page.screenshot({ path: `shots/speed-2-results-${w}.png` })
// no name yet: Share asks for one. A 2 s run is turned away; then swap in the bot's real lap and send that
await page.click("#share")
await page.waitForTimeout(800)
console.log("share, no name:", await page.evaluate(() => document.getElementById("runMsg").textContent))
await page.fill("#runName", "Tester")
await page.click("#submitRun")
await page.waitForTimeout(1200)
console.log("short run:", await page.evaluate(() => document.getElementById("runMsg").textContent))
await page.evaluate(() => { const g = __game.run.ghosts[0]; __game.run.result = { ...__game.run.result, time: g.time + 1.1, frames: [...g.frames, ...g.frames.slice(-7 * 22)] } })
await page.click("#submitRun")
await page.waitForTimeout(1500)
await page.screenshot({ path: `shots/speed-3-sent-${w}.png` })
console.log("real run:", await page.evaluate(() => document.getElementById("runMsg").textContent))
await page.context().grantPermissions(["clipboard-read", "clipboard-write"])
await page.evaluate(() => { navigator.share = undefined })
await page.click("#share")
await page.waitForTimeout(800)
console.log("share:", await page.evaluate(() => document.getElementById("runMsg").textContent), await page.evaluate(() => navigator.clipboard.readText()).catch(() => "(no clipboard)"))
console.log(errors.length ? errors.join("\n") : "no page errors")
await browser.close()
