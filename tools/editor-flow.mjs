// Editor flows: erase a piece (loop breaks, marker), put it back, test drive lands in a race.
import { chromium } from "playwright"
const browser = await chromium.launch({ args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader"] })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
const errors = []
page.on("pageerror", (e) => errors.push("pageerror: " + e.message))
await page.goto("http://localhost:4731/build")
await page.evaluate(() => localStorage.clear())
await page.reload()
await page.waitForTimeout(7000)
const status = () => page.$eval("#status", (e) => e.textContent)
console.log("start:", await status())
const piece = await page.evaluate(() => { const p = __ed.track.pieces[6]; __ed.erase(p.i, p.j); return p })
await page.waitForTimeout(1500)
console.log("erased", piece.p, "->", await status())
await page.screenshot({ path: "shots/editor-broken.png" })
await page.evaluate((p) => { __ed.setTool({ kind: "road", p: p.p }, p.r); __ed.place(p.i, p.j) }, piece)
await page.waitForTimeout(1500)
console.log("put back ->", await status())
await page.evaluate(() => { __ed.setTool({ kind: "road", p: "roadStraight" }, 0); __ed.place(6, 18) })
await page.waitForTimeout(800)
console.log("place on taken cell -> toast:", await page.$eval("#toast", (e) => e.classList.contains("on") && e.textContent))
await page.click("#test")
await page.waitForTimeout(9000)
console.log("test drive url", page.url(), "hud on:", await page.$eval("#hud", (e) => e.classList.contains("on")))
console.log(errors.length ? errors.join("\n") : "no page errors")
await browser.close()
